/**
 * Модули процесса шаблонов навыков
 *
 * Этот файл создан путём разделения устаревшего монолитного
 * файла шаблонов на модули, ориентированные на процесс.
 */
import type { SkillTemplate } from '../types.js';

export function getFeedbackSkillTemplate(): SkillTemplate {
  return {
    name: 'feedback',
    description: 'Собирает и отправляет обратную связь пользователей о OpenSpec с обогащением контекста и анонимизацией.',
    instructions: `Помогите пользователю отправить обратную связь о OpenSpec.

**Цель**: Сопроводить пользователя через сбор, обогащение и отправку обратной связи, обеспечив конфиденциальность за счёт анонимизации.

**Процесс**

1. **Соберите контекст из разговора**
   - Просмотрите недавнюю историю разговора для получения контекста
   - Определите, какая задача выполнялась
   - Отметьте, что работало хорошо или плохо
   - Зафиксируйте конкретные точки трения или похвалу

2. **Подготовьте обогащённую обратную связь**
   - Создайте ясный содержательный заголовок (одно предложение, без префикса «Обратная связь:»)
   - Напишите текст, включающий:
     - Что пользователь пытался сделать
     - Что произошло (хорошее или плохое)
     - Актуальный контекст из разговора
     - Любые конкретные предложения или запросы

3. **Анонимизируйте конфиденциальную информацию**
   - Замените пути к файлам на \`<path>\` или общие описания
   - Замените API-ключи, токены и секреты на \`<redacted>\`
   - Замените названия компаний/организаций на \`<company>\`
   - Замените личные имена на \`<user>\`
   - Замените конкретные URL на \`<url>\`, если они не публичные/актуальные
   - Сохраните технические детали, помогающие понять проблему

4. **Представьте черновик на согласование**
   - Покажите пользователю полный черновик
   - Чётко отобразите и заголовок, и текст
   - Запросите явное одобрение перед отправкой
   - Позвольте пользователю запросить правки

5. **Отправьте после подтверждения**
   - Используйте команду \`openspec feedback\` для отправки
   - Формат: \`openspec feedback "title" --body "body content"\`
   - Команда сохраняет текст заголовка в теле задачи и сокращает длинные заголовки задач GitHub
   - Команда автоматически добавит метаданные (версия, платформа, метка времени)

**Пример черновика**

\`\`\`
Заголовок: Обработка ошибок в процессе работы с артефактами требует улучшения

Текст:
Я создавал новое изменение и столкнулся с проблемой в процессе работы
с артефактами. Когда я попытался продолжить после создания
предложения, система недостаточно ясно указала, что сначала нужно завершить спецификации.

Предложение: добавить более понятные сообщения об ошибках, объясняющие цепочки
зависимостей в процессе работы с артефактами. Например: «Cannot create design.md,
потому что спецификации не завершены (выполнено 0 из 2)».

Контекст: используется управляемая спецификациями схема с <path>/my-project
\`\`\`

**Примеры анонимизации**

До:
\`\`\`
Работа в /Users/john/mycompany/auth-service/src/oauth.ts
Ошибка с API-ключом: sk_live_abc123xyz
Работа в Acme Corp
\`\`\`

После:
\`\`\`
Работа в <path>/oauth.ts
Ошибка с API-ключом: <redacted>
Работа в <company>
\`\`\`

**Ограничения**

- ДОЛЖЕН показать полный черновик перед отправкой
- ДОЛЖЕН запросить явное одобрение
- ДОЛЖЕН анонимизировать конфиденциальную информацию
- РАЗРЕШЕНО пользователю изменять черновик перед отправкой
- НЕ отправлять без подтверждения пользователя
- ВКЛЮЧАЙТЕ актуальный технический контекст
- СОХРАНЯЙТЕ специфичные для разговора наблюдения

**Требуется подтверждение пользователя**

Всегда спрашивайте:
\`\`\`
Вот черновик обратной связи, который я подготовил:

Заголовок: [title]

Текст:
[body]

Всё в порядке? Могу внести правки или отправить как есть.
\`\`\`

Продолжайте отправку только после подтверждения пользователем.`,
    license: 'MIT',
    compatibility: 'Требуется openspec CLI.',
    metadata: { author: 'openspec', version: '1.0' },
  };
}
