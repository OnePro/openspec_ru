import type { SkillTemplate, CommandTemplate } from '../types.js';
import { optionalWorkflow } from '../optional-workflow.js';
import { STORE_SELECTION_GUIDANCE } from './store-selection.js';
import { PROJECT_ROOT_GUARD } from './project-root.js';

/**
 * Передача управления команде `continue`, которая не гарантированно установлена
 * вместе с `new`; разрешается на этапе генерации (см. optional-workflow.ts).
 */
const FIRST_ARTIFACT_PROMPT = optionalWorkflow(
  'continue',
  'Выполните `/opsx:continue` или просто опишите, что это за изменение, и я его подготовлю.',
  'Просто опишите, что это за изменение, и я его подготовлю.'
);

const EXISTING_CHANGE_HINT = optionalWorkflow(
  'continue',
  'предложите вместо этого использовать `/opsx:continue`',
  'сообщите об этом и спросите, возобновить это изменение или выбрать другое имя'
);

export function getNewChangeSkillTemplate(): SkillTemplate {
  return {
    name: 'openspec-new-change',
    description: 'Начать новое изменение OpenSpec с использованием экспериментального процесса артефактов. Используйте, когда пользователь хочет создать новую функцию, исправление или доработку со структурированным пошаговым подходом. Также используйте, когда пользователь говорит «openspec new change» или «opsx new».',
    instructions: `Начните новое изменение с использованием экспериментального подхода на основе артефактов.

${STORE_SELECTION_GUIDANCE}

${PROJECT_ROOT_GUARD}

**Входные данные**: запрос пользователя должен включать имя изменения (kebab-case) ИЛИ описание того, что он хочет создать.

**Шаги**

1. **Если чёткий ввод не предоставлен, спросите, что он хочет создать**

   Спросите пользователя (открытый вопрос, без готовых вариантов):
   > «Над каким изменением вы хотите работать? Опишите, что вы хотите создать или исправить.»

   Из описания выведите имя в kebab-case (например, «add user authentication» → \`add-user-auth\`).

   **ВАЖНО**: НЕ продолжайте, пока не станет понятно, что пользователь хочет создать.

2. **Определите схему процесса**

   Используйте схему по умолчанию (без \`--schema\`), если только пользователь явно не запросил другой процесс.

   **Используйте другую схему только если пользователь упоминает:**
   - Конкретное имя схемы → используйте \`--schema <name>\`
   - «show workflows» или «what workflows» → выполните \`openspec schemas --json\` и предложите выбрать

   **В остальных случаях**: не указывайте \`--schema\`, чтобы использовать схему по умолчанию.

3. **Создайте каталог изменения**
   \`\`\`bash
   openspec new change "<name>"
   \`\`\`
   Добавьте \`--schema <name>\` только если пользователь запросил конкретный процесс.
   Это создаёт сгенерированный каркас изменения в хранилище планирования, определённом CLI.

4. **Покажите статус артефактов**
   \`\`\`bash
   openspec status --change "<name>" --json
   \`\`\`
   Используйте возвращённые \`planningHome\`, \`changeRoot\`, \`artifactPaths\` и \`nextSteps\` вместо предположений о путях внутри репозитория.

5. **Получите инструкции для первого артефакта**
   Первый артефакт зависит от схемы (например, \`proposal\` для процесса, основанного на спецификации).
   Проверьте вывод статуса, чтобы найти первый артефакт со статусом «ready».
   \`\`\`bash
   openspec instructions <first-artifact-id> --change "<name>"
   \`\`\`
   Это выводит шаблон и контекст для создания первого артефакта.

6. **ОСТАНОВИТЕСЬ и дождитесь указаний пользователя**

**Результат**

После выполнения шагов составьте сводку:
- Имя изменения и его расположение
- Используемая схема/процесс и последовательность её артефактов
- Текущий статус (готово 0/N артефактов)
- Шаблон первого артефакта
- Запрос: «Готовы создать первый артефакт? Просто опишите, что это за изменение, и я его подготовлю, или попросите меня продолжить.»

**Ограничения**
- НЕ создавайте пока никаких артефактов — только покажите инструкции
- НЕ переходите дальше показа шаблона первого артефакта
- Если имя недопустимо (не kebab-case), запросите допустимое имя
- Если изменение с таким именем уже существует, предложите вместо этого продолжить это изменение
- Передайте --schema, если используется процесс, отличный от процесса по умолчанию`,
    license: 'MIT',
    compatibility: 'Требуется CLI openspec.',
    metadata: { author: 'openspec', version: '1.0' },
  };
}

