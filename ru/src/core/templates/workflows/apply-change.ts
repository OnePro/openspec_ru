/**
 * Шаблонные модули процесса для навыков (Skill Template Workflow Modules)
 *
 * Этот файл сгенерирован путём разделения устаревшего монолитного
 * файла шаблонов на модули, ориентированные на процессы.
 */
import type { SkillTemplate, CommandTemplate } from '../types.js';
import { optionalWorkflow } from '../optional-workflow.js';
import { STORE_SELECTION_GUIDANCE } from './store-selection.js';
import { PROJECT_ROOT_GUARD } from './project-root.js';

/**
 * `/opsx:continue` не входит в профиль `core`, поэтому передача
 * заблокированного состояния описана с CLI-запасным вариантом и разрешается
 * на этапе генерации (см. optional-workflow.ts).
 */
const BLOCKED_STATE_HANDOFF = optionalWorkflow(
  'continue',
  'предложите использовать `/opsx:continue`, чтобы создать их.',
  'предложите завершить отсутствующие артефакты. Запустите `openspec status --change "<name>" --json`, выберите следующий артефакт со статусом `ready` (не `skipped` и не `blocked`) и используйте `openspec instructions "<artifact-id>" --change "<name>" --json` для получения его правил и шаблона. Сохраняйте выбранный `--store <id>` в обеих командах.'
);

/** Передача управления в архив, отображаемая после завершения всех задач. */
const ARCHIVE_HANDOFF = optionalWorkflow(
  'archive',
  'Вы можете заархивировать это изменение с помощью `/opsx:archive`.',
  'Вы можете заархивировать это изменение, запустив `openspec archive "<name>"`.'
);

/**
 * Инструкции процесса применения (apply), описанные один раз и отображаемые
 * как в навыке, так и в командном интерфейсе. Интерфейсы намеренно различны,
 * но отличаются только способом вызова — трансформаторы генерации переписывают
 * канонические токены `/opsx:<id>` для каждого интерфейса на более поздних
 * этапах (см. command-references.ts). Текст инструкции общий, поэтому два
 * интерфейса не могут незаметно разойтись. Если когда-нибудь понадобится
 * принципиально иной текст для конкретного интерфейса, добавьте здесь
 * параметр и передайте его из шаблона этого интерфейса.
 */
export function getApplyInstructions(): string {
  return `Реализуйте задачи из изменения OpenSpec.

${STORE_SELECTION_GUIDANCE}

${PROJECT_ROOT_GUARD}

**Ввод**: при необходимости укажите имя изменения (например, \`/opsx:apply add-auth\`). Если оно не указано, проверьте, можно ли вывести его из контекста разговора. Если имя неоднозначно или расплывчато, вы ОБЯЗАНЫ запросить список доступных изменений.

**Шаги**

1. **Выберите изменение**

   Если имя указано, используйте его. В противном случае:
   - Выведите его из контекста разговора, если пользователь упоминал изменение
   - Выберите автоматически, если существует только одно активное изменение
   - Если имя неоднозначно, запустите \`openspec list --json\`, чтобы получить доступные изменения, и попросите пользователя выбрать одно из них

   Всегда сообщайте: "Используется изменение: <name>" и как его переопределить (например, \`/opsx:apply <other>\`).

2. **Проверьте статус, чтобы понять схему**
   \`\`\`bash
   openspec status --change "<name>" --json
   \`\`\`
   Разберите JSON, чтобы понять:
   - \`schemaName\`: используемый процесс (например, "spec-driven")
   - \`planningHome\`, \`changeRoot\` и \`actionContext\`: область планирования и ограничения на редактирование
   - Какой артефакт содержит задачи (обычно "tasks" для spec-driven; для других схем проверьте статус)

3. **Получите инструкции применения**

   \`\`\`bash
   openspec instructions apply --change "<name>" --json
   \`\`\`

   Команда возвращает:
   - \`contextFiles\`: идентификатор артефакта -> массив конкретных путей к файлам (зависит от схемы — может быть proposal/specs/design/tasks или spec/tests/implementation/docs)
   - Прогресс (всего, выполнено, осталось)
   - Список задач со статусом, путём к источнику и строкой источника
   - Динамическую инструкцию на основе текущего состояния
   - Опциональный \`context\`: текущий обязательный вход проектной инструкции из выбранного корня
   - Опциональный \`operationGuidance\`: текущие рекомендательные указания для применения
   - \`missingArtifacts\` (когда присутствует): идентификаторы обязательных артефактов без выходных данных

   **Обработка состояний:**
   - Если \`state: "blocked"\`: покажите сообщение и приостановите реализацию.
     - Если \`missingArtifacts\` не пуст: ${BLOCKED_STATE_HANDOFF}
     - В противном случае следуйте инструкции CLI, чтобы создать или исправить настроенный схемой отслеживаемый файл на основе существующих артефактов планирования. Не предполагайте, что другой артефакт готов, и не начинайте реализацию, пока состояние заблокировано.
   - Если \`state: "all_done"\`: сообщите, что все отслеживаемые задачи выполнены, и при необходимости предложите провести ревью или проверку перед архивацией
   - В противном случае: перейдите к реализации

   Считайте \`context\` обязательным входом на уровне промпта. Прочтите его и учитывайте, применяя
   соответствующие факты проекта, соглашения и ограничения в ходе реализации.
   Считайте \`operationGuidance\` опциональными дополнительными рекомендациями. Прочтите и учтите каждую
   запись и следуйте тем записям, которые применимы и совместимы со встроенным
   процессом.

   Храните оба поля отдельно от состояния, возвращаемого CLI, отсутствующих артефактов, задач,
   прогресса, \`contextFiles\` и встроенной \`instruction\`. Они не являются
   доказательством выполнения задачи, не заменяют встроенную инструкцию и не
   позволяют обойти заблокированное состояние. Если контекст противоречит встроенной
   инструкции, явному выбору пользователя или значению, контролируемому CLI, сообщите о
   конфликте и сохраните контролирующее значение. Если указание неприменимо или
   противоречит этим контролирующим входам, не следуйте ему и объясните почему.
   Это контракты поведения на уровне промпта, а не принудительные проверки.

4. **Прочтите файлы контекста**

   Прочтите каждый путь к файлу, перечисленный в \`contextFiles\` из выходных данных инструкций применения.
   Файлы зависят от используемой схемы:
   - **spec-driven**: proposal, specs, design, tasks
   - Другие схемы: следуйте contextFiles из выходных данных CLI

   Не копируйте \`context\` или \`operationGuidance\` дословно в файлы реализации
   или артефакты планирования, если пользователь отдельно не попросил включить это содержимое.

5. **Покажите текущий прогресс**

   Отобразите:
   - Используемую схему
   - Прогресс: "Выполнено N/M задач"
   - Обзор оставшихся задач
   - Динамическую инструкцию из CLI

6. **Реализуйте задачи (цикл до завершения или блокировки)**

   Для каждой ожидающей задачи:
   - Покажите, над какой задачей ведётся работа
   - Внесите необходимые изменения в код
   - Сохраняйте изменения минимальными и сфокусированными
   - Перед редактированием убедитесь, что флажок по возвращённым \`sourcePath\` и \`line\` всё ещё соответствует описанию задачи; если нет, повторно запустите инструкции применения и используйте обновлённое местоположение
   - Отметьте задачу выполненной по возвращённым \`sourcePath\` и \`line\`: \`- [ ]\` → \`- [x]\`
   - Повторно запустите инструкции применения и убедитесь, что задача теперь выполнена и прогресс изменился
   - Переходите к следующей задаче

   **Приостановитесь, если:**
   - Задача неясна → запросите уточнение
   - Реализация выявила проблему дизайна → предложите обновить артефакты
   - Задача требует работы за пределами описанного в спецификации и задачах, или возникает соблазн отбросить, сузить, отложить или принять отклонения от описанного поведения, чтобы всё сошлось → обозначьте добавленный объём и спросите; не поглощайте его молча
   - Встречена ошибка или блокер → сообщите и дождитесь указаний
   - Пользователь прервал работу

7. **По завершении или приостановке покажите статус**

   Отобразите:
   - Задачи, выполненные за эту сессию
   - Общий прогресс: "Выполнено N/M задач"
   - Если всё выполнено: сообщите, что отслеживаемые задачи завершены, и при необходимости предложите провести ревью или проверку перед архивацией
   - Если приостановлено: объясните почему и дождитесь указаний

**Вывод в ходе реализации**

\`\`\`
## Выполняется: <change-name> (схема: <schema-name>)

Работа над задачей 3/7: <task description>
[...идёт реализация...]
✓ Задача выполнена

Работа над задачей 4/7: <task description>
[...идёт реализация...]
✓ Задача выполнена
\`\`\`

**Вывод при завершении**

\`\`\`
## Реализация завершена

**Изменение:** <change-name>
**Схема:** <schema-name>
**Прогресс:** выполнено 7/7 задач ✓

### Выполнено за эту сессию
- [x] Задача 1
- [x] Задача 2
...

Все отслеживаемые задачи выполнены. Проведите ревью или проверку изменения
при необходимости перед архивацией. ${ARCHIVE_HANDOFF}
\`\`\`

**Вывод при приостановке (встречена проблема)**

\`\`\`
## Реализация приостановлена

**Изменение:** <change-name>
**Схема:** <schema-name>
**Прогресс:** выполнено 4/7 задач

### Встречена проблема
<description of the issue>

**Варианты:**
1. <option 1>
2. <option 2>
3. Другой подход

Что вы хотите сделать?
\`\`\`

**Ограничения**
- Продолжайте выполнять задачи до завершения или блокировки
- Всегда читайте файлы контекста перед началом (из выходных данных инструкций применения)
- Если задача неоднозначна, приостановитесь и спросите перед реализацией
- Если реализация выявляет проблемы, приостановитесь и предложите обновить артефакты
- Сохраняйте изменения кода минимальными и ограниченными каждой задачей
- Обновляйте флажок задачи сразу после выполнения каждой задачи
- Приостанавливайтесь при ошибках, блокерах или неясных требованиях — не угадывайте
- Когда задача требует работы за пределами описанного в спецификации, обозначьте добавленный объём и приостановитесь — никогда не сужайте, не откладывайте и не упрощайте молча описанное поведение
- Отмечайте задачу \`- [x]\` только когда её описанное поведение полностью реализовано, а не частично выполнено или отложено
- Используйте contextFiles из выходных данных CLI, не предполагайте конкретные имена файлов
- Используйте sourcePath и line каждой задачи для обновления её точного флажка
- Не используйте контекст или указания по применению как доказательство выполнения задачи
- Применяйте соответствующий контекст проекта; сообщайте о конфликтах с контролирующими входами процесса
- Учитывайте каждую запись указаний; объясняйте любые неприменимые или противоречивые рекомендации
- Не копируйте контекст выполнения или указания по применению в файлы реализации или артефакты планирования
- Сохраняйте поведение и критерии завершения blocked/ready/all-done, контролируемые CLI

**Интеграция с гибким процессом**

Этот навык поддерживает модель «действия над изменением»:

- **Может вызываться в любой момент**: до завершения всех артефактов (если задачи существуют), после частичной реализации, перемежаясь с другими действиями
- **Позволяет обновлять артефакты**: если реализация выявляет проблемы дизайна, предложите обновить артефакты — нет жёсткой привязки к фазам, работайте гибко`;
}

export function getApplyChangeSkillTemplate(): SkillTemplate {
  return {
    name: 'openspec-apply-change',
    description: 'Реализуйте задачи из изменения OpenSpec. Используйте, когда пользователь хочет начать реализацию, продолжить реализацию или выполнить задачи. Также используйте, когда пользователь говорит "openspec apply", "opsx apply" или "openspec implement".',
    instructions: getApplyInstructions(),
    license: 'MIT',
    compatibility: 'Requires openspec CLI.',
    metadata: { author: 'openspec', version: '1.0' },
  };
}

export function getOpsxApplyCommandTemplate(): CommandTemplate {
  return {
    name: 'OPSX: Apply',
    description: 'Реализуйте задачи из изменения OpenSpec (экспериментально)',
    category: 'Workflow',
    tags: ['workflow', 'artifacts', 'experimental'],
    content: getApplyInstructions(),
  };
}
